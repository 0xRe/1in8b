const strenuous=new Set<SportId>(['football','basketball','icehockey','rugby','aussie','amfootball','gaelic','handball','waterpolo','polo','volleyball','netball','hockey','boxing','wrestling','muaythai','kunkhmer','laamb','kokboru','kabaddi','takraw','chinlone','cricket','baseball','surf']);
export function isNamedSport(id:string):id is NamedSportId{return id.startsWith('sp_')&&Object.hasOwn(SPORT_NAMES,id.slice(3));}
export function isStrenuousSport(id:string):boolean{return isNamedSport(id)&&strenuous.has(id.slice(3) as SportId);}
export function hobbyCategory(id:HobbyId):HobbyId{return isNamedSport(id)?'sport':id;}
/** Only the evidenced age restriction is modeled here; disability contexts remain separate work. */
export function hobbyPracticeBlocked(life:Life,id:string,atAge=life.age):boolean{
 if(id==='dance'||id==='hiking')return physicalFeetOff(life,atAge);
 if(!isNamedSport(id))return false;const pool=physicalSportPool(life,atAge);
 return !!pool&&!pool.includes(id.slice(3) as SportId)||atAge>=80&&isStrenuousSport(id);
}
const countrySports=(country:string):readonly SportId[]=>(COUNTRY_SPORTS as Partial<Record<string,readonly SportId[]>>)[country]??[];
export function discoverySports(life:Life):NamedSportId[]{
 if(life.age>=70&&life.stats.health<40)return [];
 const pool=physicalSportPool(life),local=pool??countrySports(life.country.id);
 return [...local,...(!pool&&!local.includes('football')?['football' as const]:[])].filter(id=>life.age<70||!strenuous.has(id)).map(id=>`sp_${id}` as NamedSportId);
}
